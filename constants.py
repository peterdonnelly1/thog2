import inspect

def console(msg_type: str, level: int = 1, message: str = "arrived here "):
    """
    Logs a message with consistent column alignment and color coding.
    
    Args:
        msg_type (str): "INFO", "WARNING", or "ERROR"
        message (str): The log message content.
    """
    if DEBUG<level:
        return
    else:
        # Determine caller module and function
        frame = inspect.currentframe().f_back
        module_name = inspect.getmodule(frame).__name__ if inspect.getmodule(frame) else "<unknown>"
        function_name = frame.f_code.co_name
        line_number = frame.f_lineno

        # Set color based on message type
        if msg_type == "HEAD":
            color = BOLD_AMETHYST
        elif msg_type == "ERROR":
            color = BOLD_RED
        elif msg_type == "WARNING":
            color = BOLD_ORANGE
        elif msg_type == "NOTE":
            color = CAMEL
        elif msg_type == "ALSO":
            color = COQUELICOT
        elif msg_type == "VALIDATION":
            color = VALIDATION
        elif msg_type == "TINT":
            color = TINT
        elif msg_type == "INFO":
            color = INFO
        else:  # Default to INFO
            color = BOLD_OLIVEGREEN

        # Format message with fixed-width columns for alignment
        log_str = (
            f"{color}{msg_type:<8}"
            f" {I_15}in module {BOLD_BLEU}{module_name:<16}{R} {color}function {BOLD_BLEU}{function_name:<20}{R}{color} line {MIKADO}{line_number:>3}: {R}{color}{message}{RESET}"
        )

        print(log_str)
